import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const load = name => readFile(new URL(name, root), 'utf8');
const modules = ['state', 'resize', 'layout', 'native-frame', 'view'];
const [manifest, sources, css, en, zh] = await Promise.all([
  load('package.json'), Promise.all(modules.map(name => load(`src/${name}.js`))),
  load('src/style.css'), load('locale/en.json'), load('locale/zh.json'),
]);
const clientSource = sources.map(source => source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '')).join('\n');
const dictionaries = { en: JSON.parse(en).ui, zh: JSON.parse(zh).ui };
if (Object.keys(dictionaries.en).sort().join() !== Object.keys(dictionaries.zh).sort().join()) {
  throw new Error('Client locale dictionaries must have matching keys');
}
const code = `// Generated by scripts/build.mjs. Edit src/ or locale/, then run npm run build.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(JSON.parse(manifest).name)},\n  factory(require) {\n${clientSource}\n    return createTilePlugin(require('react'), ${JSON.stringify(css)}, ${JSON.stringify(dictionaries)});\n  },\n});\n`;
if (process.argv.includes('--check')) {
  if (await load('client.js') !== code) throw new Error('Stale client.js: npm run build');
} else {
  await writeFile(new URL('client.js', root), code);
}
